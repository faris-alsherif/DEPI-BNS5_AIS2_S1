def add(num1 : int, num2 : int) -> int :
    """
    Function add used to sum two number

    :param num1: parameter holdes the values of number 1
    :type num1: int

    :param num2: parameter holdes the values of number 2
    :type num2: int

    :return: return the addition of two number
    :rtype: int   
    """
    return num1 + num2

def sub(num1 : int, num2 : int) -> int :
    """
    Function sub used to subtract two number

    :param num1: parameter holdes the values of number 1
    :type num1: int

    :param num2: parameter holdes the values of number 2
    :type num2: int

    :return: return the subtraction of two number
    :rtype: int   
    """
